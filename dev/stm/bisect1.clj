;; Bisect 1: raw executor submit on glojure
(require 'cohost.hosts.auto)
(require '[cohost.hosts.glj :as glj-host])
(glj-host/install!)
(require '[cohost.thread :as thread])
(println "step 1: send-executor")
(def ex (thread/send-executor))
(println "step 2: submit!")
(def ran (atom false))
(thread/submit! ex (fn [] (reset! ran true)))
(println "step 3: submitted, sleeping")
(Thread/sleep 600)
(println "worker ran?" @ran)
(println "DONE")
(System/exit 0)
