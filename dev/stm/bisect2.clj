;; Bisect 2: binding conveyance pieces on glojure
(require 'cohost.hosts.auto)
(require '[cohost.hosts.glj :as glj-host])
(glj-host/install!)
(require '[cohost.thread :as thread]
         '[cohost.adapter :as host])
(def ^:dynamic *x* 1)
(println "A: push/pop thread bindings with a var")
(host/push-thread-bindings! {(var *x*) 42})
(println "   pushed, *x* =" *x*)
(host/pop-thread-bindings!)
(println "   popped, *x* =" *x*)
(println "B: with-thread-bindings!")
(host/with-thread-bindings! {(var *x*) 7} (fn [] (println "   inside, *x* =" *x*)))
(println "C: interned-var cohost.core *agent*")
(println "   =>" (pr-str (host/interned-var 'cohost.core '*agent*)))
(println "D: resolve-core *agent*")
(println "   =>" (pr-str (host/resolve-core '*agent*)))
(println "DONE")
(System/exit 0)
