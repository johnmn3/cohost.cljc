(require 'cohost.memory 'cohost.memory-eve)
(alias 'memory 'cohost.memory)
(def v (memory/make-vector [1 2]))
(println "vec of EveVector elem:" (try (let [r (memory/make-vector [v])] (str (pr-str r) " | elem " (type (first r))))
                                       (catch Throwable e (str "ERR " (.getMessage e)))))
(println "vec of host list elem:" (try (let [r (memory/make-vector [(list 1 2)])] (str (pr-str r) " | elem " (type (first r))))
                                       (catch Throwable e (str "ERR " (.getMessage e)))))
(println "list of host Cons elem:" (try (let [r (memory/make-list [(cons 1 (list 2))])] (str (pr-str r) " | elem " (type (first r))))
                                        (catch Throwable e (str "ERR " (.getMessage e)))))
(println "map with EveVector value:" (try (let [r (memory/make-map [:a v])] (str (pr-str r) " | val " (type (get r :a))))
                                          (catch Throwable e (str "ERR " (.getMessage e)))))
(println "vec of host vector elem:" (try (let [r (memory/make-vector [[1 2]])] (str (pr-str r) " | elem " (type (first r))))
                                         (catch Throwable e (str "ERR " (.getMessage e)))))
(println :done)
