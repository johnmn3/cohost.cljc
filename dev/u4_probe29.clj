(require 'cohost.memory 'cohost.memory-eve)
(alias 'memory 'cohost.memory)
(memory/set-fill! true)
(defrecord Rec [x])
(def f (fn [x] (+ x 1)))
(def v #'f)
(def m (memory/make-map [:f f :n 1]))
(println "fn value identical:" (identical? f (memory/lookup m :f)))
(println "fn value callable:" ((memory/lookup m :f) 41))
(def mv (memory/make-map [v 42]))
(println "var key lookup:" (memory/lookup mv v))
(println "var key contains:" (memory/lookup-contains? mv v))
(def vc (memory/make-vector [\A \B]))
(println "char nth:" (memory/lookup vc 0))
(def mc (memory/make-map [\A 7]))
(println "char key, other instance:" (memory/lookup mc (Character/valueOf (char 65))))
(println "never-stored fn probe:" (memory/lookup m (fn [x] x) :nf))
(println "equiv host twin:" (memory/equiv m {:f f :n 1}))
(println "hasheq host twin:" (= (memory/hasheq m) (hash {:f f :n 1})))
(def r (->Rec 9))
(def mr (memory/make-map [:r r]))
(println "record resident identical:" (identical? r (memory/lookup mr :r)))
(def t (memory/as-transient (memory/make-map [:a 1])))
(memory/t-assoc t :g f)
(def pm (memory/t-persistent! t))
(println "transient fn persistent lookup:" (identical? f (memory/lookup pm :g)))
(println "sorted key resident dissoc:" (memory/lookup (memory/make-map [f 1]) f))
(println :done)
