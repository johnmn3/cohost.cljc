(require 'cohost.hosts.jvm 'cohost.boot 'cohost.adapter 'cohost.memory 'cohost.memory-eve)
(alias 'boot 'cohost.boot)
(def report (boot/boot! {}))
(boot/make-user-ns!)
(defn ev [label src]
  (println label (try (pr-str (boot/eval-str src))
                      (catch Throwable e (str "ERR " (type e) " " (.getMessage e))))))
(ev "class eve map:" "(class (hash-map :a 1))")
(ev "class eve list:" "(class (list 1 2))")
(ev "class eve vec:" "(class (vector 1 2 3 4 5 6 7))")
(ev "class eve set:" "(class (hash-set 1 2))")
(ev "ifn? eve list:" "(ifn? (list 1 2))")
(ev "ifn? eve vec:" "(ifn? (vector 1 2 3 4 5 6 7))")
(ev "index-of char:" "(do (require (quote [clojure.string :as s])) (nil? (s/index-of \"abc\" \\z)))")
(ev "re-matcher:" "(nil? (re-matcher #\"a\" \"abc\"))")
(println :done)
