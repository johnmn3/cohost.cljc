;; u4 probe 1: host-side Eve meta + misc
(require 'cohost.memory 'cohost.memory-eve)
(alias 'mem 'cohost.memory) (alias 'me 'cohost.memory-eve)
(def ev (mem/root (me/eve-vector [1 2 3])))
(def em (mem/root (me/eve-map {:a 1})))
(println "host with-meta vec:" (pr-str (meta (with-meta ev {:a 1}))))
(println "host with-meta map:" (pr-str (meta (with-meta em {:a 1}))))
(println "type of with-meta result:" (type (with-meta ev {:a 1})))
(println "same object?" (identical? ev (with-meta ev nil)))
(println "eve vec class:" (class ev))
(println "supers has Reversible?" (contains? (supers (class ev)) clojure.lang.Reversible))
(println "supers has Comparable?" (contains? (supers (class ev)) java.lang.Comparable))
(println "map supers IEditableCollection?" (contains? (supers (class em)) clojure.lang.IEditableCollection))
(def es (mem/root (me/eve-set #{1 2})))
(println "set supers IEditableCollection?" (contains? (supers (class es)) clojure.lang.IEditableCollection))
(def el (mem/root (me/eve-list (list 1 2))))
(println "list supers:" (sort (map str (supers (class el)))))
(println "host rseq on host vec:" (pr-str (rseq [1 2 3])))
(println "host compare vec:" (compare [1 2] [1 3]))
(println "eve map seq entry type:" (type (first (seq em))))
(println "eve vec rseq via seq reverse:" (pr-str (reverse (seq ev))))
(System/exit 0)
