;; u4 probe 4: slab ctx capacity behavior, isolated cases
(require 'cohost.hosts.jvm 'cohost.adapter
         '[eve.deftype-proto.alloc :as alloc] '[eve.vec :as eve-vec] '[eve.map :as eve-map])
(alias 'host 'cohost.adapter)
(defn t [label f] (println (str label " => " (host/try-all (fn [] (pr-str (f))) (fn [e] (str "ERR " (host/error-message e)))))))
;; isolated small cases on a default ctx each time (fresh ctx per case via binding a new one)
(defn with-ctx [opts f] (f (alloc/make-jvm-heap-slab-ctx opts)))
(defn mkmap [ctx m] (eve-map/jvm-eve-hash-map-from-offset ctx (eve-map/jvm-write-map! ctx m)))
(t "8-key map, default ctx" #(keys (with-ctx {} (fn [c] (mkmap c (zipmap [:a :b :c :d :e :f :g :h] (range)))))))
(t "100-entry map, default ctx" #(count (with-ctx {} (fn [c] (mkmap c (into {} (map (fn [i] [i i]) (range 100))))))))
(t "1000-entry map, default ctx" #(count (with-ctx {} (fn [c] (mkmap c (into {} (map (fn [i] [i i]) (range 1000))))))))
(t "10000-entry map, default ctx" #(count (with-ctx {} (fn [c] (mkmap c (into {} (map (fn [i] [i i]) (range 10000))))))))
(t "vec 100, default ctx" #(count (with-ctx {} (fn [c] (eve-vec/eve-vec c (range 100))))))
(t "vec 1000, default ctx" #(count (with-ctx {} (fn [c] (eve-vec/eve-vec c (range 1000))))))
(t "vec 100000, default ctx" #(count (with-ctx {} (fn [c] (eve-vec/eve-vec c (range 100000))))))
(t "vec 1000, big capacities" #(count (with-ctx {:capacities {0 16777216 1 16777216 2 16777216 3 16777216 4 16777216 5 16777216}} (fn [c] (eve-vec/eve-vec c (range 1000))))))
(t "200 small maps one default ctx (accumulation)" #(with-ctx {} (fn [c] (count (loop [i 0 last nil] (if (< i 200) (recur (inc i) (mkmap c {:a i})) last))))))
(t "2000 small maps one default ctx" #(with-ctx {} (fn [c] (count (loop [i 0 last nil] (if (< i 2000) (recur (inc i) (mkmap c {:a i})) last))))))
(t "assoc chain 500 on one map" #(with-ctx {} (fn [c] (count (loop [i 0 m (mkmap c {})] (if (< i 500) (recur (inc i) (assoc m i i)) m))))))
(System/exit 0)
