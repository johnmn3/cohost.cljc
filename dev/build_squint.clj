;; build_squint.clj — the squint body build driver (bb).
;;
;;   bb dev/build_squint.clj <work-dir> <main-ns> <eve-dir> <root> [<root> ...]
;;
;; One driver for the squint builds (the CLI/run body and the ring
;; body): stage every root through dev/squint_stage.clj, generate
;; the shim mirror, compile the staged tree with the squint CLI,
;; and write main.mjs. Re-runnable: staging and compilation are
;; redone from the sources each time; node_modules is installed
;; once. Local proof: run it against the same roots — the build
;; itself is the miniature; the body's --eval smoke is the run
;; proof.
;;
;; The work dir holds: stage/ (staged sources), out/ (compiled
;; modules), node_modules/ (squint-cljs + an eve-native symlink
;; to <eve-dir>), main.mjs, squint.edn.
(ns build-squint
  (:require [babashka.fs :as fs]
            [babashka.process :as p]
            [clojure.string :as str]))

(defn- run! [opts & args]
  (let [r (apply p/shell (assoc opts :continue true) args)]
    (when-not (zero? (:exit r))
      (throw (ex-info (str "command failed: " (str/join " " args)) {:exit (:exit r)})))
    r))

(def cljs-stub-source
  "(ns cohost.hosts.cljs
  \"Squint body link stub (generated by dev/build_squint.clj): the
   real cohost.hosts.cljs is the self-hosted CLJS adapter -- it
   loads the cljs.js compiler package and installs itself as the
   host adapter. The squint body installs cohost.hosts.squint
   instead; this stub carries only the vars cohost.hosts.cljs-eve
   links against, on realm paths the squint body never takes.\")

(defn fn-var-name [& _] nil)
(defn var-handle [& _] nil)
(defn var-name-root [& _] nil)
(defn var-qsym [& _] nil)
(defn set-realm-poll! [& _] nil)
")

(defn- shim-names
  "Public var names defined by cohost/shim.cljc: top-level
   def-family forms whose name carries no :private meta."
  [shim-path]
  (let [src (slurp shim-path)]
    (into []
          (comp (map second)
                (remove nil?)
                (distinct))
          (re-seq #"(?m)^\((?:def|defn|defmacro|defonce|definlines?)\s+(?!\^:private)([A-Za-z0-9_\-\+\*\!\/\?\>\<\=\'\&\%\.]+)" src))))

(defn -main [& args]
  (let [[work main-ns eve-dir & roots] args
        work (fs/absolutize work)
        stage (fs/file work "stage")
        out (fs/file work "out")]
    (fs/create-dirs work)
    ;; node_modules: squint-cljs by npm, eve-native by symlink
    (when-not (fs/exists? (fs/file work "node_modules" "squint-cljs"))
      (spit (fs/file work "package.json")
            "{\"name\":\"cohost-squint-body\",\"private\":true,\"type\":\"module\",\"dependencies\":{\"squint-cljs\":\"0.16.213\"}}")
      (run! {:dir (str work)} "npm" "install" "--no-audit" "--no-fund"))
    (let [link (fs/file work "node_modules" "eve-native")]
      (when-not (fs/exists? link)
        (fs/create-sym-link link (fs/absolutize eve-dir))))
    ;; stage the roots (squint_stage prints the staged root paths).
    ;; Roots go in absolute: squint_stage links unchanged files
    ;; with the root path as passed, and a relative root's links
    ;; resolve nowhere from inside the stage tree (measured: the
    ;; compiler then finds no namespaces and ENOENTs on files that
    ;; exist). Any link still broken after staging is dereferenced
    ;; to a real copy below.
    ;; The stage step retries as a unit: this box's write guard
    ;; refuses content writes in waves (EPERM on spit), and a
    ;; staging that dies mid-tree is discarded whole. The leash
    ;; is one variable: 60 attempts at 20 s spacing rides out a
    ;; ~20-minute wave; each attempt restages from clean.
    ;; Resume: a staged tree whose stamp matches the sources is
    ;; reused whole — the stamp is (path size mtime) over every
    ;; source file under the roots plus squint_stage.clj itself,
    ;; all metadata reads, which the write guard does not refuse.
    (let [abs-roots (map #(str (fs/absolutize %)) roots)
          stage-attempts 60
          stamp-of (fn []
                     (str/join "\n"
                               (sort (for [r abs-roots
                                           f (fs/glob r "**.{cljc,cljs,clj}")
                                           :when (fs/regular-file? f)]
                                       (str f " " (fs/size f) " " (.toMillis (fs/last-modified-time f)))))))
          stamp-file (fs/file work "stage-stamp.txt")
          want-stamp (str (stamp-of) "\n" (fs/size "dev/squint_stage.clj")
                          "\n" (fs/size "dev/build_squint.clj") " "
                          (.toMillis (fs/last-modified-time "dev/build_squint.clj")))]
      (if (and (fs/exists? stamp-file) (= want-stamp (slurp stamp-file)))
        (println "build_squint: stage stamp matches; reusing the staged tree")
        (do
      (loop [attempt 1]
        (fs/delete-tree stage)
        ;; stdout goes to a file, not a captured stream: a
        ;; stream-capturing shell call was seen to hang forever
        ;; when the stage died on the write guard.
        (let [out-file (fs/file work "stage-out.txt")
              r (apply p/shell {:continue true :out out-file :err out-file}
                       "bb" "dev/squint_stage.clj" (str stage) abs-roots)]
          (if (zero? (:exit r))
            (spit (fs/file work "stage-roots.txt") (slurp out-file))
            (if (< attempt stage-attempts)
              (do (println "build_squint: stage attempt" attempt "failed (write guard?); retrying")
                  (Thread/sleep 20000)
                  (recur (inc attempt)))
              (throw (ex-info "squint_stage failed after all attempts" {}))))))
          ;; The staging printer qualifies @x to (clojure.core/deref x);
          ;; squint's compile-time load of the cohost graph cannot
          ;; resolve the clojure.core namespace (the host core is
          ;; squint.core / cohost.core), so the qualification comes
          ;; back off in the staged tree.
          (doseq [f (fs/glob stage "**.{cljc,cljs}")]
            (when (fs/regular-file? f)
              (let [s (slurp (str f))]
                (when (str/includes? s "(clojure.core/deref ")
                  ;; never write through a staged symlink into a
                  ;; source file: replace the link with a real file
                  (when (fs/sym-link? f) (fs/delete f))
                  (spit (str f) (str/replace s "(clojure.core/deref " "(deref "))))))
          ;; deref broken links while the tree is fresh (a reused
          ;; tree was already dereferenced when it was staged)
          (doseq [f (fs/glob stage "**")]
            (when (fs/sym-link? f)
              (let [target (str (java.nio.file.Files/readSymbolicLink
                                  (.toPath (fs/file f))))]
                (when-not (fs/exists? f)
                  (let [src (if (fs/absolute? target) target (fs/file (fs/parent f) target))]
                    (when (fs/exists? src)
                      (fs/delete f)
                      (fs/copy src f)))))))
          ;; replace the staged CLJS adapter with the link stub
          (let [staged-root (first (filter #(fs/exists? (fs/file % "cohost" "hosts" "cljs.cljs"))
                                           (str/split-lines (slurp (fs/file work "stage-roots.txt")))))
                stub (fs/file staged-root "cohost" "hosts" "cljs.cljs")]
            (when (fs/sym-link? stub) (fs/delete stub))
            (spit (str stub) cljs-stub-source))
          (spit stamp-file want-stamp))))
    ;; the shim mirror, generated into the staged cohost root
    (let [shim-path (first (filter fs/exists? (map #(fs/file % "cohost" "shim.cljc") roots)))
          names (shim-names shim-path)
          staged-cohost (first (filter #(fs/exists? (fs/file % "cohost" "shim.cljc"))
                                       (str/split-lines (slurp (fs/file work "stage-roots.txt")))))
          mirror-path (fs/file staged-cohost "cohost" "squint_mirror.cljs")]
      (spit mirror-path
            (str "(ns cohost.squint-mirror\n"
                 "  \"Generated by dev/build_squint.clj: the compiled cohost.shim vars,\n"
                 "   mirrored into the squint adapter's registry.\"\n"
                 "  (:require [cohost.shim :as shim]\n"
                 "            [cohost.boot :as boot]\n"
                 "            [cohost.hosts.squint :as squint-host]))\n\n"
                 "(defn mirror! []\n"
                 "  (squint-host/mirror!\n"
                 "   {'cohost.shim {"
                 (str/join " " (map (fn [nm] (str "'" nm " shim/" nm)) names))
                 "}\n"
                 "    'cohost.boot {'rewrite-output boot/rewrite-output}}))\n"))
      ;; shim-names: the cljs build captures cohost.shim's public
      ;; names through cljs.analyzer (src/cohost/shim_names.clj,
      ;; a .clj file squint's resolver cannot see). The squint
      ;; build captures the same set from source instead: a staged
      ;; shim_names.cljc whose public-names macro expands to the
      ;; extracted set literal.
      ;; goog.object: cohost.shim requires it (the cljs build gets
      ;; it from the Closure library; squint has none). The used
      ;; subset — get, set, getValueByKeys — over plain JS objects.
      (let [gdir (fs/file staged-cohost "goog")]
        (fs/create-dirs gdir)
        (spit (fs/file gdir "object.cljs")
              (str "(ns goog.object\n"
                   "  \"Generated by dev/build_squint.clj: the goog.object subset\n"
                   "   cohost.shim uses (get, set, getValueByKeys), over plain\n"
                   "   JS objects — the Closure library's own semantics.\"\n"
                   "  (:require [cljs.core :as core]))\n\n"
                   "(defn get\n"
                   "  ([obj k] (aget obj k))\n"
                   "  ([obj k default] (let [v (aget obj k)] (if (undefined? v) default v))))\n\n"
                   "(defn set [obj k v] (aset obj k v))\n\n"
                   "(defn getValueByKeys [obj & keys]\n"
                   "  (reduce (fn [o k] (when (some? o) (aget o k))) obj keys))\n")))
      (let [sn (fs/file staged-cohost "cohost" "shim_names.clj")
            snjc (fs/file staged-cohost "cohost" "shim_names.cljc")]
        (when (fs/exists? sn) (fs/delete sn))
        (spit snjc
              (str "(ns cohost.shim-names\n"
                   "  \"Generated by dev/build_squint.clj: cohost.shim's public\n"
                   "   names, captured from source (the cljs build captures\n"
                   "   them through cljs.analyzer; see shim_names.clj).\"\n"
                   "  (:require [clojure.core]))\n\n"
                   "(defmacro public-names []\n"
                   "  (list 'quote (set '(" (str/join " " names) "))))\n"))))
    ;; squint.edn + compile. The CLI resolves :paths against its
    ;; cwd; absolute paths silently index nothing (measured: every
    ;; namespace not found), so the staged roots go in relative.
    (let [paths (str/split-lines (slurp (fs/file work "stage-roots.txt")))
          rel (map #(str "stage/" (fs/file-name (str/trim %))) paths)]
      (spit (fs/file work "squint.edn")
            (str "{:paths [" (str/join " " (map #(str "\"" % "\"") rel)) "]\n"
                 " :output-dir \"out\"}\n")))
    (fs/delete-tree out)
    (run! {:dir (str work)}
          "node" (str (fs/file work "node_modules" "squint-cljs" "lib" "cli.js"))
          "compile")
    ;; main.mjs
    (let [main-file (str "out/" (-> (str main-ns)
                                    (str/replace "-" "_")
                                    (str/replace "." "/"))
                         ".mjs")]
      (spit (fs/file work "main.mjs")
            (str "import \"./node_modules/eve-native/scripts/require_shim.mjs\";\n"
                 "import * as m from \"./" main-file "\";\n"
                 "m._main(...process.argv.slice(2));\n")))
    (println "SQUINT-BUILD-OK" (str work))))

(apply -main *command-line-args*)
