(require 'cohost.hosts.jvm 'cohost.boot 'cohost.adapter 'cohost.memory 'cohost.memory-eve)
(alias 'boot 'cohost.boot)
(def report (boot/boot! {}))
(boot/make-user-ns!)
(defn ev [label src]
  (println label (try (pr-str (boot/eval-str src))
                      (catch Throwable e (str "ERR " (.getMessage e))))))
(ev "ifn? eve list:" "(ifn? (list 1 2))")
(ev "ifn? eve vec:" "(ifn? (vector 1 2 3 4 5 6 7))")
(ev "ifn? eve map:" "(ifn? (hash-map :a 1))")
(ev "ifn? eve set:" "(ifn? (hash-set 1))")
(ev "ifn? host fn:" "(ifn? (fn [x] x))")
(ev "ifn? host list:" "(ifn? (quote (1 2)))")
(ev "call eve vec:" "((vector 10 20 30 40 50 60 70) 2)")
(ev "instance IFn list:" "(instance? clojure.lang.IFn (list 1 2))")
(println :done)
