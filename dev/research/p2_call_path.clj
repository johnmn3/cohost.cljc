;; P2, the JVM twin. The other-ns fn is defined in a second namespace here.
(ns research.p2-other) (defn id1 [x] x)
(ns user)
(defn id1 [x] x)
(defn id2 [x y] x)
(defn idv [x & ys] x)
(defmulti mm (fn [x] 0))
(defmethod mm 0 [x] x)
(def vf (volatile! id1))
(def n 5000000)
(defn loop-only [] (loop [i 0] (if (< i n) (recur (inc i)) i)))
(defn call-var-same-ns [] (loop [i 0] (if (< i n) (recur (inc (id1 i))) i)))
(defn call-var-other-ns [] (loop [i 0] (if (< i n) (recur (inc (research.p2-other/id1 i))) i)))
(defn call-local [] (let [f id1] (loop [i 0] (if (< i n) (recur (inc (f i))) i))))
(defn call-2 [] (loop [i 0] (if (< i n) (recur (inc (id2 i i))) i)))
(defn call-variadic [] (loop [i 0] (if (< i n) (recur (inc (idv i i))) i)))
(defn call-multi [] (loop [i 0] (if (< i n) (recur (inc (mm i))) i)))
(defn call-volatile-fn [] (loop [i 0] (if (< i n) (recur (inc (@vf i))) i)))
(defn run []
  (bench "loop-only" loop-only)
  (bench "call-var-same-ns" call-var-same-ns)
  (bench "call-var-other-ns" call-var-other-ns)
  (bench "call-local" call-local)
  (bench "call-2" call-2)
  (bench "call-variadic" call-variadic)
  (bench "call-multi" call-multi)
  (bench "call-volatile-fn" call-volatile-fn))
