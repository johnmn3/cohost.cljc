;; X4-1: where the stock core's sort, sort-by and str-build time goes on jank
;; (bb bench:jank cases :sort, :sort-by, :str-build, same sizes). Run under
;; cohost on jank: bash dev/research/run-cohost-jank.sh dev/research/x4_parts.clj
(def n 50000)
(def xs (doall (map (fn [i] (mod (* i 7919) 10007)) (range n))))
(def recs (mapv (fn [i] {:k (mod (* i 7919) 10007) :i i}) (range 20000)))
(defn gen-input [] (count (map (fn [i] (mod (* i 7919) 10007)) (range n))))
(defn sort-case [] (first (sort (map (fn [i] (mod (* i 7919) 10007)) (range n)))))
(defn sort-realized [] (first (sort xs)))
(defn to-arr [] (alength (to-array xs)))
(defn arr-sort-host-compare [] (let [a (to-array xs)] (java.util.Arrays/sort a) (aget a 0)))
(defn arr-sort-stock-compare [] (let [a (to-array xs)] (java.util.Arrays/sort a compare) (aget a 0)))
(defn seq-arr [] (first (seq (to-array xs))))
(defn compare-1e6 [] (loop [i 0 acc 0] (if (< i 1000000) (recur (inc i) (+ acc (compare i 500000))) acc)))
(defn sort-by-case [] (:i (first (sort-by :k recs))))
(defn sort-by-cmp-only [] (let [a (to-array recs)] (java.util.Arrays/sort a (fn [x y] (compare (:k x) (:k y)))) (:i (aget a 0))))
(defn str-build [] (count (apply str (map str (range 20000)))))
(defn map-str [] (count (doall (map str (range 20000)))))
(def strs (doall (map str (range 20000))))
(defn apply-str [] (count (apply str strs)))
(def v1e6 (vec (range 1000000)))
(defn reduce-vec [] (reduce + 0 v1e6))
(defn reduce-range [] (reduce + 0 (range 1000000)))
(defn transduce-1e5 [] (transduce (comp (map inc) (filter odd?)) + (range 100000)))
(defn into-vector-1e5 [] (count (into [] (map inc) (range 100000))))
(defn run []
  (bench "gen-input-5e4" gen-input)
  (bench "sort-case-5e4" sort-case)
  (bench "sort-realized-5e4" sort-realized)
  (bench "to-array-5e4" to-arr)
  (bench "arr-sort-host-compare-5e4" arr-sort-host-compare)
  (bench "arr-sort-stock-compare-5e4" arr-sort-stock-compare)
  (bench "seq-array-5e4" seq-arr)
  (bench "compare-1e6" compare-1e6)
  (bench "sort-by-case-2e4" sort-by-case)
  (bench "sort-by-cmp-only-2e4" sort-by-cmp-only)
  (bench "str-build-2e4" str-build)
  (bench "map-str-2e4" map-str)
  (bench "apply-str-2e4" apply-str)
  (bench "reduce-vec-1e6" reduce-vec)
  (bench "reduce-range-1e6" reduce-range)
  (bench "transduce-1e5" transduce-1e5)
  (bench "into-vector-1e5" into-vector-1e5))
