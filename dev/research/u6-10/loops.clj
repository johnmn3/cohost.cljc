;; U6-10: loops whose locals are not typed natively on jank (U6-7's gap (c)). Under cohost on jank:
;;   bash dev/research/run-cohost-jank.sh dev/research/u6-10/loops.clj   (JANK_BIN picks the binary)
;; on the JVM: (cat dev/research/harness.clj dev/research/u6-10/loops.clj; echo '(run)') | clojure -M -
;; dloop / iloop are the order's pair shapes ((loop [i 0 x 0.5 acc 0.0] ...), (+ acc (* i 3))).
(def s1e6 (apply str (repeat 1000000 \a)))
(def v1e5 (vec (map double (range 100000))))
(defn snth [] (loop [i 0 n 0] (if (< i 1000000) (recur (inc i) (if (= \a (nth s1e6 i)) (inc n) n)) n)))
(defn snth-count [] (let [c (count s1e6)] (loop [i 0 n 0] (if (< i c) (recur (inc i) (if (= \a (nth s1e6 i)) (inc n) n)) n))))
(defn snth-plus [] (loop [i 0 n 0] (if (< i 1000000) (recur (inc i) (+ n (if (= \a (nth s1e6 i)) 1 0))) n)))
(defn if-inc [] (loop [i 0 n 0] (if (< i 1000000) (recur (inc i) (if (odd? i) (inc n) n)) n)))
(defn loop-only [] (loop [i 0 n 0] (if (< i 1000000) (recur (inc i) (inc n)) n)))
(defn count-bound [] (let [c (count v1e5)] (loop [i 0 n 0] (if (< i c) (recur (inc i) (+ n i)) n))))
(defn dsum [] (loop [i 0 acc 0.0] (if (< i 100000) (recur (inc i) (+ acc (nth v1e5 i))) acc)))
(defn dloop [] (loop [i 0 x 0.5 acc 0.0] (if (< i 1000000) (recur (inc i) (+ x 0.25) (+ acc x)) acc)))
(defn iloop [] (loop [i 0 acc 0] (if (< i 1000000) (recur (inc i) (+ acc (* i 3))) acc)))
(defn run []
  (println "checks" (pr-str [(snth) (snth-count) (snth-plus) (if-inc) (loop-only) (count-bound) (dsum) (dloop) (iloop)]))
  (bench "snth" snth)
  (bench "snth-count" snth-count)
  (bench "snth-plus" snth-plus)
  (bench "if-inc" if-inc)
  (bench "loop-only" loop-only)
  (bench "count-bound" count-bound)
  (bench "dsum" dsum)
  (bench "dloop" dloop)
  (bench "iloop" iloop))
