(require '[cohost.boot-cljs :as bc])
(def ctx (bc/boot!))
(println "BOOT-OK")
(bc/compile-source! ctx "hiccups/runtime.cljs" true)
(println "RUNTIME-OK")
(defn ev [s] (try (let [v (bc/eval-cljs ctx s)] (if (.isNull v) "null" (.asString v)))
                 (catch Throwable t (str "THREW: " (ex-message t)))))
(bc/eval-cljs ctx "(ns proof.hic (:require-macros [hiccups.core :as hc]))")
(def got (ev "(hiccups.core/html [:div#app.cls [:p \"hi\"]])"))
(println "html =>" (pr-str got))
(println (if (= got "<div class=\"cls\" id=\"app\"><p>hi</p></div>") "HICCUPS-PASS" "HICCUPS-FAIL"))
(def got2 (ev "(hiccups.core/html [:ul (for [i [1 2]] [:li i])])"))
(println "html2 =>" (pr-str got2))
