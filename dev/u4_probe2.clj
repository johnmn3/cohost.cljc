;; u4 probe 2: shim class-of on Eve values, host-side
(require 'cohost.hosts.jvm 'cohost.shim 'cohost.memory 'cohost.memory-eve)
(alias 'shim 'cohost.shim) (alias 'mem 'cohost.memory) (alias 'me 'cohost.memory-eve)
(def ev (mem/root (me/eve-vector [1 2 3])))
(def em (mem/root (me/eve-map {:a 1})))
(def es (mem/root (me/eve-set #{1 2})))
(def el (mem/root (me/eve-list (list 1 2))))
(println "vector? ev:" (vector? ev) "map? em:" (map? em) "set? es:" (set? es) "list? el:" (list? el))
(println "class-of ev:" (shim/class-of ev))
(println "class-of em:" (shim/class-of em))
(println "class-of es:" (shim/class-of es))
(println "class-of el:" (shim/class-of el))
(println "instance? IPersistentVector ev:" (shim/instance-of? 'clojure.lang.IPersistentVector ev))
(println "instance? Reversible ev:" (shim/instance-of? 'clojure.lang.Reversible ev))
(println "instance? IEditableCollection em:" (shim/instance-of? 'clojure.lang.IEditableCollection em))
(println "instance? IEditableCollection ev:" (shim/instance-of? 'clojure.lang.IEditableCollection ev))
(println "instance? Comparable ev:" (shim/instance-of? 'java.lang.Comparable ev))
(println "seq? el:" (seq? el) "seq? (seq ev):" (seq? (seq ev)))
(println "type el:" (type el))
(System/exit 0)
