(alias 'boot 'cohost.boot)
(alias 'memory 'cohost.memory)
(def report (boot/boot! {}))
(boot/make-user-ns!)
(def t (boot/eval-str "(transient (vector 1 2 3 4 5 6 7))"))
(println "host-side transient-value?" (memory/transient-value? t) "kind:" (memory/transient-kind t))
(println "host-side RT-count:" (try ((resolve 'cohost.shim/RT-count) t) (catch Throwable e (str "ERR " (.getMessage e)))))
(println "host-side -count:" (try ((resolve 'cohost.shim/-count) t) (catch Throwable e (str "ERR " (type e) " " (.getMessage e)))))
(println "booted count fn:" (boot/eval-str "count"))
(println "eval RT-count:" (try (boot/eval-str "(cohost.shim/RT-count (transient (vector 1 2 3 4 5 6 7)))") (catch Throwable e (str "ERR " (.getMessage e)))))
