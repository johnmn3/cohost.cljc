(require 'cohost.hosts.jvm 'cohost.boot 'cohost.adapter 'cohost.memory 'cohost.memory-eve)
(alias 'boot 'cohost.boot)
(alias 'memory 'cohost.memory)
(def report (boot/boot! {}))
(boot/make-user-ns!)
(boot/eval-str "(def u4-probe-x 1)")
(def vh (boot/eval-str "(var u4-probe-x)"))
(println "var handle type:" (type vh))
(println "representable?" (try (memory/representable? vh) (catch Throwable e (str "ERR " (.getMessage e)))))
(println "make-map with it:" (try (let [m (memory/make-map [vh 5])] (str "ok, lookup -> " (pr-str (memory/lookup m vh))))
                                  (catch Throwable e (str "ERR " (type e) " " (.getMessage e) " data:" (pr-str (ex-data e))))))
(println :done)
