(require 'cohost.hosts.jvm 'cohost.boot 'cohost.adapter 'cohost.memory 'cohost.memory-eve)
(alias 'boot 'cohost.boot)
(alias 'memory 'cohost.memory)
(def report (boot/boot! {}))
(boot/make-user-ns!)
(boot/eval-str "(def u4-probe-x 1)")
(def m (boot/eval-str "(hash-map (var u4-probe-x) 5)"))
(def vh (boot/eval-str "(var u4-probe-x)"))
(println "map type:" (type m) "var type:" (type vh))
(println "host lookup:" (try (memory/lookup m vh) (catch Throwable e (str "ERR " (type e) " " (.getMessage e)))))
(println "host contains:" (try (memory/lookup-contains? m vh) (catch Throwable e (str "ERR " (type e) " " (.getMessage e)))))
(println "eve get raw:" (try (get m vh) (catch Throwable e (str "ERR " (type e) " " (.getMessage e)))))
(println :done)
